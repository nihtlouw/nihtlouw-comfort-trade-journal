export const LOCALE_STORAGE_KEY = "bloom-ui-locale:v1";

export function readStoredLocale(): AppLocale {
  if (typeof window === "undefined") return "en";
  try {
    const saved = window.localStorage.getItem(LOCALE_STORAGE_KEY);
    return saved === "id" ? "id" : "en";
  } catch {
    return "en";
  }
}

export function writeStoredLocale(locale: AppLocale) {
  if (typeof window === "undefined") return;
  try {
    window.localStorage.setItem(LOCALE_STORAGE_KEY, locale);
  } catch {
    // Ignore storage quota / privacy mode errors.
  }
}

export function translateMarket(market: string, locale: AppLocale): string {
  if (locale !== "id") return market;
  const map: Record<string, string> = {
    Forex: "Forex",
    Stocks: "Saham",
    Crypto: "Kripto",
    Futures: "Futures",
    Commodities: "Komoditas",
  };
  return map[market] ?? market;
}

export function translateMood(mood: string, locale: AppLocale): string {
  if (locale !== "id") return mood;
  const map: Record<string, string> = {
    Calm: "Tenang",
    Focused: "Fokus",
    Anxious: "Cemas",
    Tired: "Lelah",
  };
  return map[mood] ?? mood;
}

export function translateSide(side: "Long" | "Short" | string, locale: AppLocale): string {
  if (locale !== "id") return side;
  if (side === "Long") return "Long (Beli)";
  if (side === "Short") return "Short (Jual)";
  return side;
}

export function translateAttachmentStage(stage: AttachmentStage, locale: AppLocale): string {
  if (locale !== "id") return stage;
  const map: Record<AttachmentStage, string> = {
    Before: "Sebelum",
    Entry: "Entri",
    After: "Sesudah",
    HTF: "HTF",
  };
  return map[stage] ?? stage;
}

export function translatePlaybookGroup(group: PlaybookRule["group"], locale: AppLocale): string {
  if (locale !== "id") return group;
  const map: Record<PlaybookRule["group"], string> = {
    "Before trading": "Sebelum trading",
    "While trading": "Saat trading",
    "After trading": "Setelah trading",
  };
  return map[group] ?? group;
}

export function translateAccountName(name: string, locale: AppLocale): string {
  if (locale === "id" && name === "Main account") return "Akun utama";
  return name;
}

export function greetingText(locale: AppLocale, hour = new Date().getHours()): string {
  if (locale === "id") {
    if (hour < 11) return "Selamat pagi";
    if (hour < 15) return "Selamat siang";
    if (hour < 18) return "Selamat sore";
    return "Selamat malam";
  }
  return hour < 12 ? "Good morning" : hour < 17 ? "Good afternoon" : "Good evening";
}

export function periodLabel(period: Period, locale: AppLocale): string {
  if (locale === "id") {
    return period === "ALL" ? "Semua waktu" : period === "1W" ? "7 hari terakhir" : period === "1M" ? "30 hari terakhir" : "90 hari terakhir";
  }
  return period === "ALL" ? "All time" : period === "1W" ? "Last 7 days" : period === "1M" ? "Last 30 days" : "Last 90 days";
}

